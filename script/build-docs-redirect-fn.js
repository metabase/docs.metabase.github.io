#!/usr/bin/env node
"use strict";

// Generates the viewer-request CloudFront Function that performs version-conditional
// /docs redirects, from conditional-redirects.json.
//
// Amplify's static custom-rules (redirects.json) can only match URL patterns, so a
// version-templated rule fires for EVERY version and 404s wherever the target page
// wasn't built. This function instead parses the version segment and only redirects
// when the version qualifies (`latest`/`master`, or `v0.NN` within a rule's inclusive
// [minVersion, maxVersion] band; maxVersion is optional/open-ended). Otherwise it
// leaves the request untouched (keeps serving the original page). Bands let one source
// map to different targets across version ranges, so redirects resolve in a single hop.
//
// The emitted function is deployed to the fronting CloudFront distribution's /docs/*
// viewer-request event by the website repo (see update-docs-redirect-fn.yml). It must
// stay within the CloudFront Functions limits (<10 KB, ES5.1, synchronous, no I/O).
//
// Usage:
//   node script/build-docs-redirect-fn.js [--config <path>] [--out <path>]
// Prints the function to stdout, or writes it to --out.

const fs = require("fs");
const path = require("path");

const VERSION_PLACEHOLDER = "<version>";

function parseArgs(argv) {
  const args = { config: "conditional-redirects.json", out: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--config") args.config = argv[++i];
    else if (argv[i] === "--out") args.out = argv[++i];
    else throw new Error("Unknown argument: " + argv[i]);
  }
  return args;
}

// Escape a literal string so it can be embedded inside a JS regex literal (/.../),
// including the "/" delimiter and characters inside a character class.
function escapeForRegexLiteral(str) {
  return str.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
}

// Turn a source like "/docs/<version>/developers-guide/contributing" into a regex
// literal string that captures the version segment: the placeholder becomes a
// single-segment capture group, everything else is matched literally, and an optional
// trailing slash is allowed.
function sourceToRegexLiteral(source) {
  if (source.indexOf(VERSION_PLACEHOLDER) === -1) {
    throw new Error(
      "source must contain " + VERSION_PLACEHOLDER + ": " + source,
    );
  }
  const literal = source
    .split(VERSION_PLACEHOLDER)
    .map(escapeForRegexLiteral)
    .join("([^\\/]+)");
  return "/^" + literal + "\\/?$/";
}

// Parse a version string such as "0.52" (also accepts "v0.52" / "v0.52.1") into the
// pieces the emitted function needs. Metabase's major is always 0/1, so we gate on
// the minor. `field` names the property for error messages. Returns
// { label: "v0.52", minor: 52 }.
function parseVersion(value, index, field) {
  if (typeof value !== "string") {
    throw new Error(
      "Rule " +
        index +
        " `" +
        field +
        '` must be a version string like "0.52", got: ' +
        JSON.stringify(value),
    );
  }
  const m = value.match(/^v?([01])\.(\d+)/);
  if (!m) {
    throw new Error(
      "Rule " +
        index +
        " has an invalid `" +
        field +
        "`: " +
        JSON.stringify(value),
    );
  }
  return { label: "v" + m[1] + "." + m[2], minor: Number(m[2]) };
}

function validateRule(rule, index) {
  if (!rule || typeof rule !== "object") {
    throw new Error("Rule " + index + " is not an object");
  }
  if (typeof rule.source !== "string") {
    throw new Error("Rule " + index + " is missing a string `source`");
  }
  if (typeof rule.target !== "string") {
    throw new Error("Rule " + index + " is missing a string `target`");
  }
  const min = parseVersion(rule.minVersion, index, "minVersion");
  // `maxVersion` is optional; when present it must not be below `minVersion`.
  let max = null;
  if (rule.maxVersion !== undefined) {
    max = parseVersion(rule.maxVersion, index, "maxVersion");
    if (max.minor < min.minor) {
      throw new Error(
        "Rule " +
          index +
          " has `maxVersion` (" +
          max.label +
          ") below `minVersion` (" +
          min.label +
          ")",
      );
    }
  }
  return { min, max };
}

function buildFunction(rules) {
  const ruleEntries = rules
    .map((rule, i) => {
      const { min, max } = validateRule(rule, i);
      const regex = sourceToRegexLiteral(rule.source);
      const target = JSON.stringify(rule.target);
      const range = max ? `${min.label}–${max.label}` : `>= ${min.label}`;
      const maxLiteral = max ? String(max.minor) : "null";
      return (
        `  // ${rule.source}  (${range})\n` +
        `  { re: ${regex}, minVersion: ${min.minor}, maxVersion: ${maxLiteral}, target: ${target} },`
      );
    })
    .join("\n");

  return `// AUTO-GENERATED by script/build-docs-redirect-fn.js — do not edit by hand.
// Source of truth: conditional-redirects.json
// Version-conditional /docs redirects for the fronting CloudFront distribution.

function qualifies(version, minVersion, maxVersion) {
  // \`latest\` and \`master\` point at the newest docs. They qualify for open-ended
  // rules, but an upper-bounded rule (maxVersion set) must NOT match them — they are
  // newer than any concrete maxVersion.
  if (version === "latest" || version === "master") {
    return maxVersion === null;
  }
  // Match \`v0.NN\` / \`v1.NN\` (and the bare \`0.NN\` form defensively); compare the minor.
  var m = version.match(/^v?[01]\\.(\\d+)/);
  if (!m) {
    return false;
  }
  var minor = Number(m[1]);
  return minor >= minVersion && (maxVersion === null || minor <= maxVersion);
}

function redirect(location) {
  return {
    statusCode: 301,
    statusDescription: "Moved Permanently",
    headers: { location: { value: location } },
  };
}

var RULES = [
${ruleEntries}
];

function handler(event) {
  var request = event.request;
  var uri = request.uri;

  for (var i = 0; i < RULES.length; i++) {
    var m = uri.match(RULES[i].re);
    if (m && qualifies(m[1], RULES[i].minVersion, RULES[i].maxVersion)) {
      return redirect(RULES[i].target.replace(${JSON.stringify(VERSION_PLACEHOLDER)}, m[1]));
    }
  }
  return request;
}
`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const configPath = path.resolve(args.config);
  const raw = fs.readFileSync(configPath, "utf8");
  const rules = JSON.parse(raw);
  if (!Array.isArray(rules)) {
    throw new Error(configPath + " must contain a JSON array");
  }
  const output = buildFunction(rules);

  if (args.out) {
    fs.mkdirSync(path.dirname(path.resolve(args.out)), { recursive: true });
    fs.writeFileSync(args.out, output);
    process.stderr.write(
      "Wrote " +
        Buffer.byteLength(output) +
        " bytes to " +
        args.out +
        " from " +
        rules.length +
        " rule(s)\n",
    );
  } else {
    process.stdout.write(output);
  }
}

module.exports = {
  buildFunction,
  sourceToRegexLiteral,
  escapeForRegexLiteral,
  parseVersion,
  validateRule,
  parseArgs,
  main,
};

if (require.main === module) {
  main();
}
