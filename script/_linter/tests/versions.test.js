const invalidTestCases = [
  `a-metabase-version.123`,
  `v2.123`,
  `<a%20onclick="window.alert(%27hacked%27)"><h1>hacked%20-%20click%20me</h1></a>`, // HTML/script injection
  `&gt;a%20onclick="window.alert(%27hacked%27)"&lt;&gt;h1>hacked%20-%20click%20me&gt;/h1&lt;&gt;/a&lt;`, // HTML/script injection
];

// Valid version tag
// - valid chars only
// - starts with "v"
// - has at least 2 dots
function isValidVersionTag(versionTagStr) {
  return /^v\d+(\.\d+){2,}(-[a-zA-Z\d-]+)?$/.test(versionTagStr);
}

describe("Metabase versions", () => {
  describe("Metabase versions regex against actual version tag", () => {
    test.each(versionsTestCases)(
      `%p should be a valid version tag`,
      (testCaseStr) => {
        expect(isValidVersionTag(testCaseStr)).toBe(true);
      },
    );
  });

  describe("Invalid Metabase versions", () => {
    test.each(invalidTestCases)(
      `%p should be an invalid version`,
      (testCaseStr) => {
        expect(isValidVersionTag(testCaseStr)).toBe(false);
      },
    );
  });
});
